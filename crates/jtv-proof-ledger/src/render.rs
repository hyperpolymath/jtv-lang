//! Rendering the derived grades as AsciiDoc.
//!
//! The output is deterministic: it depends only on the records, the receipts
//! and the digests of the files on disk, so `check` can compare it with the
//! committed copy byte for byte.

use crate::{
    currency, derive, Correspondence, Currency, Evidence, Leg, Pwg, Receipt, Records, Route, Token,
};
use std::collections::BTreeMap;
use std::fmt::Write as _;

fn route(r: Route) -> &'static str {
    match r {
        Route::Transported => "transported",
        Route::ReProved => "re-proved",
        Route::Waived => "waived",
        Route::Unavailable => "unavailable",
    }
}

fn state(s: Correspondence) -> &'static str {
    match s {
        Correspondence::AgdaPending => "AGDA-PENDING",
        Correspondence::BridgePending => "BRIDGE-PENDING",
        Correspondence::Reconciled => "RECONCILED",
        Correspondence::Counterexample => "COUNTEREXAMPLE",
        Correspondence::Quarantined => "QUARANTINED",
    }
}

fn currency_label(c: &Currency) -> String {
    match c {
        Currency::Current => "current (every input digest matches)".into(),
        Currency::Missing => "*missing*".into(),
        Currency::Stale(files) => format!("*stale* — changed since the run: {}", files.join(", ")),
    }
}

fn leg_cell(leg: Option<&Leg>, graded: Option<&(Token, bool)>) -> String {
    match (leg, graded) {
        (Some(l), Some((tok, counts))) => {
            let decl = l
                .decl
                .as_deref()
                .map_or("—".to_string(), |d| format!("`{d}`"));
            format!(
                "{decl} +\n{} · {} · {} · counts: {}",
                route(l.route),
                tok.label(),
                state(l.state),
                if *counts { "yes" } else { "no" }
            )
        }
        _ => "—".into(),
    }
}

/// Escape a table cell's pipe characters.
fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

pub struct Inputs<'a> {
    pub records: &'a Records,
    pub agda: Option<&'a Receipt>,
    pub agda_now: &'a BTreeMap<String, String>,
    pub lean: Option<&'a Receipt>,
    pub lean_now: &'a BTreeMap<String, String>,
}

/// Render the grade census, receipt currency and per-theorem results as
/// AsciiDoc. The supplied current digests determine receipt currency; missing
/// receipts are shown as missing and do not contribute evidence.
pub fn render(i: &Inputs) -> String {
    let agda_cur = currency(i.agda, i.agda_now);
    let lean_cur = currency(i.lean, i.lean_now);
    let ev = Evidence {
        agda: i.agda,
        agda_current: agda_cur == Currency::Current,
        lean: i.lean,
        lean_current: lean_cur == Currency::Current,
    };
    let graded: Vec<_> = i
        .records
        .theorems
        .iter()
        .map(|t| (t, derive(t, &ev)))
        .collect();

    let mut counts = [0usize; 4];
    for (_, g) in &graded {
        counts[g.pwg as usize] += 1;
    }
    let mut o = String::new();
    let _ = writeln!(o, "// SPDX-License-Identifier: CC-BY-SA-4.0");
    let _ = writeln!(
        o,
        "// GENERATED by `cargo run -p jtv-proof-ledger -- render`. Do not edit by hand:"
    );
    let _ = writeln!(
        o,
        "// change verification/ledger/theorems.json or re-run a receipt, then re-render."
    );
    let _ = writeln!(o, "// CI runs `jtv-proof-ledger check`, which fails if this file differs from a fresh render.");
    let _ = writeln!(o);
    let _ = writeln!(o, "*PWG census* ({} theory theorems): PWG-1 0 · PWG-2ii {} · PWG-2i {} · PWG-3 {} · ungraded {}.",
        graded.len(), counts[Pwg::TwoIi as usize], counts[Pwg::TwoI as usize], counts[Pwg::Three as usize], counts[Pwg::Ungraded as usize]);
    let _ = writeln!(o, "PWG-1 is never derived here: it needs per-commit receipts from a headless, isolated checker for every witness.");
    let _ = writeln!(o);
    let _ = writeln!(o, ".Receipts");
    let _ = writeln!(o, "[cols=\"1,2,2,2,3\",options=\"header\"]");
    let _ = writeln!(o, "|===");
    let _ = writeln!(
        o,
        "|Prover |Checker |Libraries and flags |Base commit, date |Currency"
    );
    for (name, r, c) in [("Agda", i.agda, &agda_cur), ("Lean", i.lean, &lean_cur)] {
        match r {
            Some(r) => {
                let _ = writeln!(
                    o,
                    "\n|{name} |{} |{} +\n{} |`{}`{} +\n{} |{}",
                    cell(&r.checker),
                    cell(&r.libraries.join(", ")),
                    cell(&r.flags.join(" ")),
                    r.base_commit,
                    if r.worktree_clean {
                        ""
                    } else {
                        " (with the uncommitted changes the digests record)"
                    },
                    r.date,
                    cell(&currency_label(c))
                );
            }
            None => {
                let _ = writeln!(o, "\n|{name} |— |— |— |*missing*");
            }
        }
    }
    let _ = writeln!(o, "|===");
    let _ = writeln!(o);
    let _ = writeln!(o, ".Per-theorem grades");
    let _ = writeln!(o, "[cols=\"3,3,2,4,2,1\",options=\"header\"]");
    let _ = writeln!(o, "|===");
    let _ = writeln!(
        o,
        "|Theorem |Agda source |Agda leg |Lean leg |Rocq leg |PWG"
    );
    for (t, g) in &graded {
        let agda = t.agda.as_ref().map_or("— (no Agda source)".into(), |a| {
            format!("`{}` +\n`{}`", a.module, a.name)
        });
        let _ = writeln!(
            o,
            "\n|*{}* +\n{} |{} |{} |{} |{} |{}",
            t.id,
            cell(&t.statement),
            agda,
            g.agda.label(),
            cell(&leg_cell(t.lean.as_ref(), g.lean.as_ref())),
            cell(&leg_cell(t.rocq.as_ref(), g.rocq.as_ref())),
            g.pwg.label()
        );
    }
    let _ = writeln!(o, "|===");
    let _ = writeln!(o);
    let _ = writeln!(o, ".Correspondence notes and residual assumptions (§2.2)");
    for (t, _) in &graded {
        let Some(l) = &t.lean else { continue };
        if l.comparison.is_empty() && l.assumptions.is_empty() {
            continue;
        }
        let _ = writeln!(o, "\n`{}`:: {}", t.id, l.comparison);
        for a in &l.assumptions {
            let _ = writeln!(o, "* {a}");
        }
    }
    o
}
